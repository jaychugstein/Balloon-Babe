# Packs Balloon Babe's art into the FX flash chip (Arduboy FX, FX-C, POOM) and writes ../BalloonBabe/fxdata.h and
# ../BalloonBabe/fxdata/fxdata.bin. Run babe2.py, portrait.py and logo3.py first. Small tables (BABE_W/H, CHEST_AT) stay in sprites.h.
import os, pickle, numpy as np
ART = os.path.dirname(os.path.abspath(__file__)); OUT = os.path.join(ART, '..', 'BalloonBabe')
def sprite(frames):                      # masked, [ink, solid] per frame -> FX dbmMasked: image byte (1 = white), mask byte
    n, _, H, W = frames.shape; out = bytearray([W >> 8, W & 255, H >> 8, H & 255])
    for ink, sol in frames:
        for p in range((H + 7) // 8):
            for x in range(W):
                rows = [p * 8 + k for k in range(8)]
                out.append(sum(int(r < H and sol[r, x] and not ink[r, x]) << k for k, r in enumerate(rows)))
                out.append(sum(int(r < H and (sol[r, x] or ink[r, x])) << k for k, r in enumerate(rows)))
    return bytes(out)
a = np.load(os.path.join(ART, 'babe2.npy'))                     # cropped the same way as export.py
ys, xs = np.nonzero(a[:, 1].any(axis=0)); a = a[:, :, ys.min():ys.max() + 1, xs.min():xs.max() + 1]
tv = np.load(os.path.join(ART, 'babe2_torso.npy')); sk = np.load(os.path.join(ART, 'babe2_skirt.npy'))
v, cap, ink, mask, bcx = [r for r in pickle.load(open(os.path.join(ART, 'logo.pkl'), 'rb')) if r[0] == 'outline_shadow' and r[1] == 15][0]
logo = np.stack([ink, mask])[None]
parts = [('FX_BABE', sprite(a), 'her 6 poses: stand, crouch, rise, top, fall, land'),
         ('FX_CHEST', sprite(tv), 'her chest in 5 bounce positions (-2..+2)'),
         ('FX_SKIRT', sprite(sk), 'skirt: hanging, swinging, flipped up'),
         ('FX_LOGO', sprite(logo), 'title logo: BALLOON with balloon O\'s, BABE outlined'),
         ('FX_PORTRAIT', sprite(np.load(os.path.join(ART, 'portrait.npy'))[None]), 'her portrait for the how-to-play talk, 52x64')]
data = bytearray(); hdr = []
for name, blob, note in parts:
    hdr.append('constexpr uint24_t %-9s = 0x%06X;   // %s' % (name, len(data), note)); data += blob
while len(data) % 256: data.append(0xFF)
page = 0x10000 - len(data) // 256
os.makedirs(os.path.join(OUT, 'fxdata'), exist_ok=True)
open(os.path.join(OUT, 'fxdata', 'fxdata.bin'), 'wb').write(data)
h = '// generated by art/fxpack.py - do not edit\n#pragma once\n#include <ArduboyFX.h>\n'
h += 'constexpr uint16_t FX_DATA_PAGE = 0x%04X;   // %d bytes of FX data\n' % (page, len(data)) + '\n'.join(hdr) + '\n'
h += 'constexpr uint8_t LOGO_W = %d, LOGO_H = %d, LOGO_BABE_CX = %d;   // BABE\'s centre, from the logo\'s left edge\n' % (ink.shape[1], ink.shape[0], int(round(bcx)))
open(os.path.join(OUT, 'fxdata.h'), 'w').write(h); print(h)
